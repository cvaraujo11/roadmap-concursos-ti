export function knowledgeName(slug: string) {
  return knowledge.find((item) => item.slug === slug)?.name ?? slug;
}

export function areaName(slug: string) {
  return areas.find((item) => item.slug === slug)?.name ?? slug;
}

export function topicName(slug: string) {
  return topics.find((item) => item.slug === slug)?.name ?? slug;
}

export function orgFamilyName(slug: string) {
  return orgFamilies.find((item) => item.slug === slug)?.name ?? slug;
}

export function topicsForKnowledge(slug: string) {
  return topics.filter((item) => item.knowledge === slug);
}
