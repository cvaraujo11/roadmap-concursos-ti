export const ufToStateName = Object.fromEntries(
  Object.entries(stateNameToUf).map(([name, uf]) => [uf, name]),
) as Record<string, string>;

const city = (
  id: string,
  contestId: string,
  trackId: string,
  uf: string,
  cityName: string,
  latitude: number,
  longitude: number,
  sourceNote: string,
): ContestLocation => ({
  id,
  contestId,
  trackId,
  scope: "municipio",
  precision: "cidade",
  uf,
  city: cityName,
  latitude,
  longitude,
  label: `${cityName} / ${uf}`,
  sourceNote,
});

const state = (
  id: string,
  contestId: string,
  trackId: string,
  uf: string,
  latitude: number,
  longitude: number,
  sourceNote: string,
): ContestLocation => ({
  id,
  contestId,
  trackId,
  scope: "estado",
  precision: "estado",
  uf,
  latitude,
  longitude,
  label: ufToStateName[uf] ?? uf,
  sourceNote,
});

const unresolved = (
  id: string,
  contestId: string,
  trackId: string,
  scope: "multiplos-estados" | "nacional",
  label: string,
  sourceNote: string,
): ContestLocation => ({
  id,
  contestId,
  trackId,
  scope,
  precision: "nao-geocodificado",
  label,
  sourceNote,
});

